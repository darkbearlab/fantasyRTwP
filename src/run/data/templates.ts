/**
 * 關卡模板（SPEC_SLICE6 §1）：每塊模板是一張文字地圖，一個字元＝1 m 的一格；一個區塊 16 × 16。
 * 模板可以佔多個區塊（size，例：關鍵地點 2 × 2）；拼接時可以旋轉、鏡像。拼接邏輯見 src/run/templateLevelGen.ts。
 *
 * 圖例：
 *   .  地板          #  牆（擋路、擋視線）      o  石柱（同牆，小型）
 *   "  草叢（隱匿）   ~  淺水（減速）           =  矮籬（掩體）
 *   W  深水（擋路、不擋視線）                  D  木門（相連的 D 是同一扇門）
 *   S  英雄出生點（起點模板）                  E  出口（S6-2 才使用，現在當地板）
 *   B  頭目位置      R  援軍進場點（頭目戰吼）
 *   1–9 生怪磚：設定在 spawns；同一塊模板裡同一個數字＝一個小隊，敵人從池子（levelPools.ts）抽
 *
 * x 軸＝文字的左右（畫面上往上是 +x，玩家往畫面上方推進），y 軸＝文字的上下。全部是佔位內容。
 */

export interface SpawnTile {
  /** 從哪個池子抽（src/run/data/levelPools.ts） */
  pool: string;
  /** 抽幾隻（包含兩端） */
  count: [number, number];
  /** 埋伏（喜歡躲在草叢裡的小隊；目前只是標記） */
  ambush?: boolean;
  /** 精英關卡：這個小隊的第一名換成隊長 */
  captain?: boolean;
}

export interface LevelTemplate {
  id: string;
  /** 標籤：章節主題（dungeon…）＋用途（start 起點、filler 填充、feature 大型景點、elite 精英房、boss 頭目房） */
  tags: string[];
  /** 抽中的權重 */
  weight: number;
  /** 佔幾個區塊 [寬, 高]；文字地圖的大小必須是 16 × 寬、16 × 高 */
  size: [number, number];
  rows: string[];
  spawns: Record<string, SpawnTile>;
}

